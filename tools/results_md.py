#!/usr/bin/env python3
"""Write docs/results.md: every table in the study, computed from data/ (no hand-copied numbers)."""
import os, runpy, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
g = runpy.run_path(os.path.join(ROOT, "report", "gen.py"), run_name="results")
med = g["med"]
L = ["# Results", "", "Generated by `tools/results_md.py` from `data/`. Medians unless stated.", ""]
def tab(head, rows):
    L.append("| " + " | ".join(head) + " |"); L.append("|" + "---|" * len(head))
    for r in rows: L.append("| " + " | ".join(str(c) for c in r) + " |")
    L.append("")
sp = g["stackp"]
L.append("## Connection layer (ms)")
tab(["Operation", "p50", "p95", "n"], [[k, f'{v["p50"]:.1f}', f'{v["p95"]:.1f}', v["n"]] for k, v in sp.items()])
tab(["Path to vLLM", "TTFT p50 (ms)"], [["direct :8101", f'{g["ttft_direct"]:.1f}'], ["llama-swap :8100", f'{g["ttft_swap"]:.1f}'], ["SSH tunnel from Mac", f'{g["ttft_tunnel"]:.1f}']])
L.append("## Agent harness (one-word turn)")
tab(["Harness", "wall (s)", "model part (s)"], [["Claude Code", f'{g["cc_wall"]:.2f}', f'{g["cc_api"]:.2f} (API)'], ["OpenCode", f'{g["oc_wall"]:.2f}', "–"],
     ["Kiro @qwen, before", f'{g["kb_wall"]:.2f}', f'{g["kb_pre"]:.2f} (prefill)'], ["Kiro @qwen, volatile tool last", f'{g["ka_wall"]:.2f}', f'{g["ka_pre"]:.2f} (prefill, {g["ka_cached"]:,} cached)']])
L.append("## vLLM: TTFT and TPOT vs. prompt length (Qwen3.8-27B AWQ)")
G = g["G"]
tab(["prompt tokens", "cold TTFT (ms)", "cached TTFT (ms)", "TPOT (ms)"], [[f'{G[(s,"cold")]["ptok"]:,}', f'{G[(s,"cold")]["ttft"]:,.0f}', f'{G[(s,"hit")]["ttft"]:,.0f}', f'{G[(s,"cold")]["tpot"]:.1f}'] for s in g["sizes"]])
tab(["concurrency", "mean TTFT (ms)", "max TTFT (ms)", "TPOT (ms)", "throughput (tok/s)"], [[c["concurrency"], f'{c["ttft_ms"]:,.0f}', f'{c["ttft_max"]:,.0f}', f'{c["tpot_ms"]:.1f}', f'{c["throughput"]:.1f}'] for c in g["conc"]])
L.append("## Kernels"); tab(["config", "8K cold prefill", "31K cold prefill", "prefill tok/s", "TPOT", "2-way tok/s"], g["krows"])
L.append("## MTP speculative decoding"); tab(["config", "TPOT (summary)", "coding tok/s (reasoning)", "accept rate (reasoning)", "coding tok/s (no reasoning)", "2-way tok/s"], g["srows"])
L.append("## Profiler: share of GPU time")
for k in ("prefill", "decode"):
    gg, ctx = g["pgroups"][k]; tot = sum(gg.values())
    tab([k, "ms", "%"], [[n, f"{v:,.1f}", f"{v/tot*100:.1f}"] for n, v in gg.most_common()])
L.append("## Media")
tab(["Z-Image", "seconds (warm median)"], [[r[0], f"{r[1]:.2f}"] for r in g["zrows"]])
tab(["TTS text", "chars", "audio", "synthesis", "RTF"], g["tts_rows"])
tab(["Wan length", "steps", "total", "denoise", "per step", "after denoise"], g["wan_rows"])
tab(["swap to", "seconds"], [[a, f"{b:.0f}"] for a, b, _, _ in g["swap"]])
L.append("## Collaboration (trial 2, fixed config; trial 1 had an 8K output cap)")
rows = []
for x in sorted(g["runs"], key=lambda x: (x["trial"], x["arm"], x["task"])):
    e = x["extra"]
    rows.append([x["trial"], g["ARM"][x["arm"]], x["task"], x["state"], x["rounds"], f'{x["passed"]}/{x["total"]}', f'{x["r1"]}' if x["r1"] is not None else "–",
                 f'{e["passed"]}/{e["total"]}' if e else "–", f'{x["wall"]:.0f}', f'{x["cost"]:.3f}', x["cl_out"], x["q_out"], x["q_reason"], x["plan_out"] or "–"])
tab(["trial", "arm", "task", "state", "rounds", "hidden tests", "round-1 tests", "edge tests", "wall (s)", "Claude $", "Claude out tok", "Qwen gen tok", "Qwen reasoning tok", "Codex out tok"], rows)
q = g["qsplit"]; w = g["qwall"]
L.append(f"Qwen time split over all coder runs: model {q['model']/w*100:.1f}%, tools {q['tool']/w*100:.1f}%, gaps {q['gap']/w*100:.1f}%; reasoning {q['reason']:,} of {q['reason']+q['out']:,} generated tokens.")
open(os.path.join(ROOT, "docs", "results.md"), "w").write("\n".join(L) + "\n")
print("wrote docs/results.md", len(L), "lines")
